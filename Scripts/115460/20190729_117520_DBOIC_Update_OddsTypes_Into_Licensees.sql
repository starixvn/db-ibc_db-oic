DECLARE @OddsTypes VARCHAR(100) = '';
DECLARE @LicenseeId INT = 0;

DECLARE @BusinessCursor as CURSOR

SET @BusinessCursor = CURSOR FOR
SELECT 
	s.c.query('./licenseeId').value('.', 'int') as LicenseeId,
	s.c.query('./oddsTypes').value('.', 'varchar(100)') as OddsTypes
FROM @xmlInfo.nodes('/licensees/licensee') AS s(c)

-- open cursor
OPEN @BusinessCursor

FETCH NEXT FROM @BusinessCursor INTO @LicenseeId, @OddsTypes;

WHILE @@FETCH_STATUS = 0
BEGIN
 	
	IF EXISTS (SELECT l.LicenseeId 
				FROM dbo.Licensee l WITH(NOLOCK)
				WHERE l.LicenseeId = @LicenseeId)
	BEGIN
		MERGE	dbo.LicenseeOddsType lot
		USING	(SELECT	CONVERT(INT, val) AS OddsTypeId FROM dbo.strSplit(@OddsTypes, ',')) t
			ON	lot.OddsTypeId = t.OddsTypeId 
				AND lot.LicenseeId = @LicenseeId
		WHEN NOT MATCHED BY TARGET THEN INSERT(LicenseeId, OddsTypeId) VALUES (@LicenseeId, t.OddsTypeId)
		WHEN NOT MATCHED BY SOURCE AND lot.LicenseeId = @LicenseeId THEN DELETE;
	END
	ELSE 
		BEGIN
			PRINT @LicenseeId
		END
	
	-- next cursor
	FETCH NEXT FROM @BusinessCursor INTO @LicenseeId, @OddsTypes;
END

--close and release cursor
CLOSE @BusinessCursor;
DEALLOCATE @BusinessCursor;

